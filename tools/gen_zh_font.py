#!/usr/bin/env python3
"""Build the flash-resident 12x12 Traditional Chinese glyph subset (zh_font.h).

Font: Fusion Pixel Font 12px monospaced zh_hant (SIL OFL 1.1),
https://github.com/TakWolf/fusion-pixel-font. The TTF (about 6 MB) is not kept
in git; it is downloaded to build/ on first use. pip install Pillow fonttools.
"""
from pathlib import Path
import argparse, hashlib, io, json, re, urllib.request, zipfile
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
VERSION = '2025.03.14'
URL = ('https://github.com/TakWolf/fusion-pixel-font/releases/download/'
       f'{VERSION}/fusion-pixel-font-12px-monospaced-ttf-v{VERSION}.zip')
MEMBERS = ['fusion-pixel-12px-monospaced-' + v + '.ttf' for v in ('zh_hant', 'zh_hans', 'ja')]
FONT = ROOT / 'build/fonts' / MEMBERS[0]
SOURCES = ('*.ino', '*.h', '*.cpp')

def ensure_fonts():
    """zh_hant first; zh_hans and ja only fill rare glyphs it lacks."""
    paths = [FONT.parent / m for m in MEMBERS]
    if not all(p.exists() for p in paths):
        FONT.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(URL, timeout=120) as r:
            z = zipfile.ZipFile(io.BytesIO(r.read()))
        for m, p in zip(MEMBERS, paths):
            p.write_bytes(z.read(m))
    return paths

def generate():
    files = sorted(p for pat in SOURCES for p in ROOT.glob(pat) if p.name != 'zh_font.h')
    chars = sorted({c for p in files for lit in re.findall(r'"([^"\n]*)"', p.read_text(encoding='utf-8'))
                    for c in lit if ord(c) > 127})
    paths = ensure_fonts()
    cmaps = [TTFont(p).getBestCmap() for p in paths]
    pick = {c: next((i for i, m in enumerate(cmaps) if ord(c) in m), None) for c in chars}
    missing = [c for c, i in pick.items() if i is None]
    if missing:
        raise SystemExit('Missing font glyphs: ' + ''.join(missing))
    fonts = [ImageFont.truetype(str(p), 12) for p in paths]
    bitmaps = []
    for ch in chars:
        font = fonts[pick[ch]]
        im = Image.new('1', (12, 12))
        adv = round(font.getlength(ch))
        ImageDraw.Draw(im).text(((12 - adv) // 2, 0), ch, font=font, fill=1)
        bits = [im.getpixel((x, y)) != 0 for y in range(12) for x in range(12)]
        assert any(bits), f'Blank glyph: {ch}'
        bitmaps.append([sum(bits[i + j] << (7 - j) for j in range(8)) for i in range(0, 144, 8)])
    out = '#pragma once\n// Generated by tools/gen_zh_font.py; Fusion Pixel Font 12px, SIL OFL 1.1.\n#include <stdint.h>\n'
    out += f'#define ZH_GLYPH_COUNT {len(chars)}\n'
    out += 'static const uint32_t ZH_CODEPOINTS[] = {\n' + ','.join(str(ord(c)) for c in chars) + '\n};\n'
    out += 'static const uint8_t ZH_BITMAPS[][18] = {\n'
    out += ''.join('  {' + ','.join(f'0x{b:02x}' for b in row) + '},\n' for row in bitmaps) + '};\n'
    return out, {'glyphs': len(chars), 'bitmap_bytes': len(chars) * 18,
                 'font_sha256': hashlib.sha256(b''.join(p.read_bytes() for p in paths)).hexdigest(), 'characters': ''.join(chars)}

if __name__ == '__main__':
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); a = p.parse_args()
    out, info = generate(); target = ROOT / 'zh_font.h'
    if a.check:
        assert target.read_text(encoding='utf-8') == out, 'Font is stale; regenerate it.'
    else:
        target.write_text(out, encoding='utf-8', newline='\n')
        (ROOT / 'localization/font-coverage.json').write_text(json.dumps(info, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f"PASS: {info['glyphs']} Unicode glyphs, {info['bitmap_bytes']} bitmap bytes")
